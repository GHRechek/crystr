// Scans assets/faces and writes lib/faces/manifest.ts. Run after changing the
// asset set: `node scripts/build-face-manifest.mjs`.
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = "assets/faces";

const list = (dir) => {
  const full = join(ROOT, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full)
    .filter((f) => f.endsWith(".png") && !f.endsWith("_shadow.png"))
    .map((f) => f.replace(/\.png$/, ""))
    .sort();
};

const hasShadow = (dir, name) => existsSync(join(ROOT, dir, `${name}_shadow.png`));

const DIRS = [
  "body", "cloths", "neck", "mouth", "nose", "beard", "eyes", "brows",
  "glasses", "hair/base", "hair/front", "hair/back", "ears", "horns",
];

// Clothing is the one layer whose files are sub-layers of a single outfit
// (<base>_primary, _secondary, _details) rather than alternatives to it.
// Grouped here so a chosen outfit always draws its whole self.
const PARTS = ["primary", "secondary", "details"];

function outfits(dir) {
  const files = new Set(
    readdirSync(join(ROOT, dir)).filter((f) => f.endsWith(".png")).map((f) => f.replace(/\.png$/, "")),
  );
  const bases = [...new Set(
    [...files].map((f) => f.replace(/_(primary|secondary|details|shadow)$/, "")),
  )].sort();

  return bases.map((name) => ({
    name,
    shadow: files.has(`${name}_shadow`),
    parts: PARTS.filter((p) => files.has(`${name}_${p}`)),
  }));
}

// Hair is three files pretending to be three choices. <name> is the layer
// *under* the face, <name> in hair/front is what covers the forehead, and
// <name>_decoration01 is a clip belonging to that style. Chosen separately
// you get bald heads wearing hairclips, so a hairstyle is grouped here and
// always draws its whole self.
//
// The kept list is the styles that read as a complete head of hair: every
// one with a matching front, plus the standalone bases with visible hair of
// their own. Dropped are the under-layers (bald alone), the decorations, and
// male05/08/09, which read as missing hair rather than short hair.
const HAIR_KEEP = [
  "female01", "female02", "female03", "female04", "female06", "female07",
  "female08", "female09", "female10", "female11", "female12", "female14",
  "male01", "male02", "male03", "male04", "male06", "male07", "male10",
  "ponytail01",
];

// Not hair: worn in it. Pulled out into their own optional layer.
const HAIR_ACCESSORIES = [
  { name: "earrings", path: "hair/base/earrings" },
  { name: "headset", path: "hair/base/headset" },
  { name: "ribbon", path: "hair/base/ribbon" },
  { name: "ear_cover01", path: "hair/front/ear_cover01" },
  { name: "ear_cover02", path: "hair/front/ear_cover02" },
  { name: "ear_cover03", path: "hair/front/ear_cover03" },
  { name: "ear_cover04", path: "hair/front/ear_cover04" },
];

function hairstyles() {
  const has = (rel) => existsSync(join(ROOT, `${rel}.png`));
  return HAIR_KEEP.filter((name) => has(`hair/base/${name}`)).map((name) => ({
    name,
    shadow: has(`hair/base/${name}_shadow`),
    decoration: has(`hair/base/${name}_decoration01`),
    front: has(`hair/front/${name}`) ? name : null,
    frontShadow: has(`hair/front/${name}_shadow`),
  }));
}

const manifest = {};
for (const d of DIRS) {
  if (d === "cloths") manifest[d] = outfits(d);
  else if (d === "hair/base") manifest[d] = hairstyles();
  else if (d === "hair/front") continue; // derived from the hairstyle
  else manifest[d] = list(d).map((name) => ({ name, shadow: hasShadow(d, name) }));
}

manifest["hair/accessory"] = HAIR_ACCESSORIES.map((a) => ({
  ...a,
  shadow: existsSync(join(ROOT, `${a.path}_shadow.png`)),
}));

const body = `// GENERATED by scripts/build-face-manifest.mjs — do not edit by hand.
// Artwork: V-ktor/pixel-art-portraits, MIT. See assets/faces/LICENSE.

export type FaceAsset = {
  name: string;
  shadow: boolean;
  /** cloths: the sub-layers of one outfit. */
  parts?: string[];
  /** hair: a clip belonging to this style. */
  decoration?: boolean;
  /** hair: the front piece this style draws over the forehead. */
  front?: string | null;
  frontShadow?: boolean;
  /** hair accessories live in two directories; this is the real path. */
  path?: string;
};

export const MANIFEST: Record<string, FaceAsset[]> = ${JSON.stringify(manifest, null, 2)};
`;

writeFileSync("lib/faces/manifest.ts", body);
console.log(
  Object.entries(manifest).map(([k, v]) => `${k}: ${v.length}`).join("  "),
);
