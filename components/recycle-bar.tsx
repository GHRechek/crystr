/** A small deterministic random, so the flakes never jump between renders. */
function rng(seed: number) {
  let a = seed * 2654435761 + 1;
  return () => { a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
}
const FLAKE_COLORS = ["#e0398a", "#e0398a", "#c04aa8", "#9184d9", "#9184d9", "#7a86e0", "#4c7df0"];

/** An empty aura: a little mound of CRYSTR pixels with flakes rising off it, where a Historikal goes. */
export function Aura({ seed, size = 46 }: { seed: number; size?: number }) {
  const bits = useMemo(() => {
    const r = rng(seed + 7);
    const pick = () => FLAKE_COLORS[Math.floor(r() * FLAKE_COLORS.length)];
    const mound = [[40, [[4, 8], [14, 10], [26, 6], [34, 8]]], [37, [[8, 6], [16, 6], [28, 6]]], [34, [[12, 4], [30, 3]]]] as [number, number[][]][];
    const base = mound.flatMap(([y, xs]) => xs.map(([x, w]) => ({ x, y, w, c: pick() })));
    const flakes = Array.from({ length: 30 }, () => {
      const start = 24 + Math.floor(r() * 17);
      const sz = start > 30 ? [2, 2, 3, 3, 3, 4][Math.floor(r() * 6)] : [2, 2, 3][Math.floor(r() * 3)];
      return { x: 4 + Math.floor(r() * 39), y: start, sz, c: pick(), dx: Math.floor(r() * 11) - 5, delay: -(r() * 2.6), dur: 1.6 + r() * 1.6 };
    });
    return { base, flakes };
  }, [seed]);
  const k = size / 46;
  return (
    <span aria-hidden style={{ position: "relative", display: "block", width: size, height: size, overflow: "hidden" }}>
      {bits.base.map((b, i) => <b key={`b${i}`} style={{ position: "absolute", left: b.x * k, top: b.y * k, width: b.w * k, height: 3 * k, background: b.c }} />)}
      {bits.flakes.map((f, i) => <i key={i} className="hk-flake" style={{ position: "absolute", left: f.x * k, top: f.y * k, width: f.sz * k, height: f.sz * k, background: f.c, animationDelay: `${f.delay}s`, animationDuration: `${f.dur}s`, ["--dx" as string]: `${f.dx * k}px` }} />)}
    </span>
  );
}

/** The bar under MY HISTORIKALS: four auras to drop Historikals of one rarity into, the recycle symbol in
 *  the middle. Tap a filled aura to take it back out; tap the symbol to recycle (it asks first). */
export function RecycleBar({ spots, onClear, onRecycle }: {
  spots: (ShownBadge | null)[];
  onClear: (i: number) => void;
  onRecycle: () => void;
}) {
  const spot = (i: number) => {
    const b = spots[i];
    return (
      <span key={i} data-spot={i} style={{ width: 46, height: 46, display: "grid", placeItems: "center", flex: "none" }}>
        {b ? (
          <button type="button" className="bv-item" onClick={() => onClear(i)} aria-label={`${b.title}: take it back out`} style={{ lineHeight: 0 }}><BadgeFace b={b} size={44} /></button>
        ) : <Aura seed={i} />}
      </span>
    );
  };
  return (
    <div style={{ flex: "none", padding: "8px 14px 8px", backgroundImage: GRAD, backgroundSize: "100% 1px", backgroundRepeat: "no-repeat", backgroundPosition: "top" }}>
      <div style={{ display: "flex", alignItems: "center", justifyContent: "space-evenly" }}>
        {spot(0)}{spot(1)}
        <button type="button" className="hk-recycle" onClick={onRecycle} aria-label="Mana Blend: these four become one of the next tier" style={{ background: "none", border: 0, padding: 0, cursor: "pointer", lineHeight: 0 }}><RecycleIcon /></button>
        {spot(2)}{spot(3)}
      </div>
    </div>
  );
}
